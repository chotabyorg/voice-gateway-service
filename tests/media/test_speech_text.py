import pytest

from voice_gateway.media.speech_text import pronounce_byn


@pytest.mark.parametrize(
    "text,expected",
    [
        ("Стрижка — 50 BYN.", "Стрижка — 50 белорусских рублей."),
        ("1 BYN, 2 BYN, 5 BYN", "1 белорусский рубль, 2 белорусских рубля, 5 белорусских рублей"),
        ("11 BYN и 21 BYN", "11 белорусских рублей и 21 белорусский рубль"),
        ("22 BYN", "22 белорусских рубля"),
        ("BYN 49.90", "49 белорусских рублей 90 копеек"),
        ("12,01 BYN", "12 белорусских рублей 1 копейка"),
        ("12,02 BYN", "12 белорусских рублей 2 копейки"),
        ("50.00 BYN", "50 белорусских рублей"),
        ("0,5 BYN", "0 белорусских рублей 50 копеек"),
        ("1 021 BYN", "1021 белорусский рубль"),
        ("1\u00a0022 byn", "1022 белорусских рубля"),
        ("Стоимость в BYN", "Стоимость в белорусских рублях"),
        ("50 USD, 10 EUR, RUB и BYNUMBER", "50 USD, 10 EUR, RUB и BYNUMBER"),
    ],
)
def test_byn_amounts(text, expected):
    assert pronounce_byn(text) == expected
