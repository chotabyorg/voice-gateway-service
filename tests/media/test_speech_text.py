        ("BYN 12.01 в 18:00", "BYN 12.01 в 18 часов"),
        ("123456789012, +1234567, +1234567890123456", "123456789012, +1234567, +1234567890123456"),
        ("id+375291112233x, ++375291112233", "id+375291112233x, ++375291112233"),
